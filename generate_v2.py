def pick_songs(day: datetime.date) -> list[str]:
    """今日の2曲を決定論で選ぶ。★LLMに選ばせない（実在しない曲を語らせないため）。

    ★2曲目のオフセットを1曲目から導出してはいけない（2026-09-04 実測でバグ）。
    当初 j = (i + 1 + T % (n-1)) % n としたら、7919 mod 11 = -1 で i が毎日1減り、
    T % 10 が毎日1増えて**完全に打ち消し合い、2曲目が毎日同じ曲に固定された**。
    → 独立した素数で別々に払い出し、衝突した時だけずらす。

    ★2026-09-05 実データ（プロハン提供の806曲）に切り替え。
      **1曲目と2曲目でプールが違う**:
        1曲目 … 280秒以上、かつプロハンさんが×を付けなかった 91曲。
                この曲の間におたよりを生成するので、短い曲を引いてはいけない。
        2曲目 … 尺の制約なし。全曲から。

    ★★曲は**曲名だけで扱ってはいけない**（2026-09-05 実データで発覚）。
      同じ曲名で歌手が違う曲が39件ある（「DJ慕情」は3人が歌っている）。
      曲名しか持たないと、こずえが**違う歌手名を言う**。曲そのものを持ち回る。
    """
    p1, p2 = song_pools()
    t = day.toordinal()
    a = p1[(t * 7919) % len(p1)]
    b = p2[(t * 4001) % len(p2)]
    if (b["title"], b["artist"]) == (a["title"], a["artist"]):
        b = p2[((t * 4001) + 1) % len(p2)]
    return [a, b]


