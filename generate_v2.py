def load_chat(outdir: Path, log: logging.Logger) -> dict:
    """おたよりの元ネタを取る。実チャット → 無ければ試作用の作り物。

    ★実チャットは `v2/chat_collect.py` が放送中（曲1の間）に書き出す。
      パスBはそれを読むだけにして、**取得の失敗がパスBを巻き込まない**ようにしている。
      0件でも例外にしない。0件なら「おたよりゼロ」としてフォールバック版が出る。
    """
    live = outdir / "chat_live.json"
    if live.exists():
        d = json.loads(live.read_text(encoding="utf-8"))
        msgs = d.get("messages", [])
        log.info("実チャットを使用: %d件 (%s)", len(msgs), live.name)
        if msgs:
            return {"messages": msgs}
        log.warning("実チャットが0件 → おたよりゼロの回として進む")
        return {"messages": []}
    log.warning("実チャットが無い → 試作用の fake_chat.json を使う")
    return json.loads((V2 / "fake_chat.json").read_text(encoding="utf-8"))


def run(pass_name: str, no_audio: bool, model: str, traffic_live: bool) -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    log = logging.getLogger("v2")
    day = datetime.date.today()
    outdir = OUTBASE / day.isoformat()
    outdir.mkdir(parents=True, exist_ok=True)

    t0 = time.time()
    if pass_name == "a":
        pack = build_pack(day, log, traffic_live)
        (outdir / "datapack.json").write_text(
            json.dumps(pack, ensure_ascii=False, indent=2), encoding="utf-8")
        log.info("テーマ: %s", pack["theme_of_today"])
        log.info("曲1: %s / %s (%ds) / 曲2: %s / %s",
                 pack["song1"]["title"], pack["song1"]["artist"], pack["song1"]["sec"],
                 pack["song2"]["title"], pack["song2"]["artist"])
        prompt = PROMPT_A.format(
            character=CHARACTER, rules=COMMON_RULES,
            datapack=json.dumps(pack, ensure_ascii=False, indent=2))
    else:
        pack = json.loads((outdir / "datapack.json").read_text(encoding="utf-8"))
        chat = load_chat(outdir, log)
        kept, dropped = filter_chat(chat["messages"])
        for d in dropped:
            log.warning("チャット除外[%s]: %s", d["_why"], d["text"][:40])
        log.info("チャット %d件中 %d件を採用", len(chat["messages"]), len(kept))
        mails = "\n".join(f"- {m['author']}さん: {m['text']}" for m in kept)
        prompt = PROMPT_B.format(
            character=CHARACTER, rules=COMMON_RULES,
            theme=pack["theme_of_today"], mails=mails,
            song2=f'{pack["song2"]["title"]}（歌: {pack["song2"]["artist"]}）')

    (outdir / f"prompt_{pass_name}.txt").write_text(prompt, encoding="utf-8")
    script = v1.generate_script_claude(prompt, model, log)
    (outdir / f"script_{pass_name}.md").write_text(script, encoding="utf-8")
    segs = v1.parse_segments(script)
    log.info("台本OK: %s", [s[0] for s in segs])

    # ★読みの二次防御。ニュースの固有名詞は事前検査できない無限集合なので、
    #   せめて「何と読まれたか」を毎朝残して気づけるようにする（v2/yomi_check.py 参照）。
    from v2 import yomi_check
    yomi_check.write(segs, outdir.resolve(), log)

    if not no_audio:
        files = v1.render_kozue(segs, outdir, log, refs=REF_MAP)
        log.info("音声OK: %s", [f.name for f in files])

    log.info("=== パス%s 完了 %.1f秒 ===", pass_name.upper(), time.time() - t0)
    if pass_name == "b":
        log.info("★このパスBの所要が、曲1(約4〜5分)の間に収まるかが勝負どころ")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--pass", dest="pass_name", choices=["a", "b"], default="a")
    ap.add_argument("--no-audio", action="store_true")
    ap.add_argument("--model", default="sonnet")
    ap.add_argument("--traffic-live", action="store_true")
    a = ap.parse_args()
