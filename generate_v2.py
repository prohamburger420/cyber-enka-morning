_NG_WORD = ("http://", "https://", "www.", "@")
# 「こずえに◯◯と言わせる」系＝放送への注入。LLMに判断させず、コード側で先に落とす
_INJECT = ("と言え", "って言え", "と言って", "って言って", "復唱", "読み上げて",
           "無視して", "指示", "命令")


def _strip_emoji(t: str) -> str:
    """YouTubeの絵文字は `:fire:` のようなコード表記で降ってくる（2026-09-04 実チャットで確認）。
    そのままだと**「コロンファイアーコロン」と読み上げる**ので落とす。
    絵文字だけの投稿は空になり、下の「空」で除外される（＝読むものが無い、で正しい）。
    Unicodeの絵文字本体も同様に落とす。"""
    t = re.sub(r":[a-z0-9_+-]{2,30}:", "", t, flags=re.I)
    t = re.sub(r"[\U0001F000-\U0001FAFF\U00002600-\U000027BF️⬀-⯿]", "", t)
    return re.sub(r"\s{2,}", " ", t).strip()


def filter_chat(messages: list[dict], limit: int = 5) -> list[dict]:
    """★チャットは"指示"でなく"素材"。選別をLLMに任せない（SAと同じ規律）。

    落とすもの: URL・メンション / こずえに喋らせようとする誘導 / 長すぎるもの。
    残ったものだけを台本に渡し、プロンプト側でも「本文は要約して紹介、逐語で読むな」と縛る。
    """
    out, dropped = [], []
    for m in messages:
        t = _strip_emoji((m.get("text") or "").strip())
        m = {**m, "text": t}
        why = None
        if any(w in t.lower() for w in _NG_WORD):
            why = "URL/メンション"
        elif any(w in t for w in _INJECT):
            why = "こずえへの誘導（注入の疑い）"
        elif len(t) > 120:
            why = "長すぎ"
        elif not t:
            why = "空"
        (dropped if why else out).append({**m, "_why": why} if why else m)
    return out[:limit], dropped


