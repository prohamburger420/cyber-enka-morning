"""台本が作れなかった日のための台本（v2構成）。2026-09-05

★これは「最後の砦」。APIが落ちても、鍵が切れても、**番組は無音にしない**。
  v1にも同名の仕組みがあったが、v1は曲1曲の構成だったので `song_of_today` を
  参照して落ちた（2026-09-05 実測）。最後の砦が落ちたら意味がない。

★★何パターンか持って日替わりで回す（2026-09-05 nordw指摘）。
  1種類しか無いと、フォールバックが2日続いた時点で**まったく同じ放送**になり、
  機械が喋っていることが露呈する。ブロックごとに文面を数種類持ち、日付で選ぶ。
  ⚠ 当初「ブロックごとに別の素数」で回そうとしたが**3日周期になった**（実測）。
    選択肢が3つなら (t×素数) mod 3 は t mod 3 の関数でしかなく、素数を変えても無駄。
    → 日付とブロック識別子を混ぜたハッシュで選ぶ。14日ぶん全部ちがうことを demo() で検査。

★中身は実データだけで組む。**LLMを使わないので事実を創作する余地がない**。
  面白さは落ちるが、嘘は言わない。
"""


def _pick(options: list[str], day_ord: int, key: int) -> str:
    """★「ブロックごとに別の素数」では**駄目**だった（2026-09-05 実測で3日周期）。
    選択肢が3つなら (t×素数) mod 3 は結局 **t mod 3 の関数**にしかならず、
    どの素数を使っても全ブロックが同じ3日周期で同時に切り替わる。
    → 日付とブロック識別子を**混ぜたハッシュ**で選ぶ。ブロックごとに位相がばらけ、
      3択×6ブロックでも組み合わせは十分に散る。"""
    import hashlib
    h = hashlib.md5(f"{key}:{day_ord}".encode()).digest()
    return options[int.from_bytes(h[:4], "big") % len(options)]


def _weather_line(pack: dict, t: int) -> str:
    # ★実物は {"source":..., "regions":[{region, city, text, temp_max, ...}]} という形。
    #   当初リストだと思い込んで w[0] を取り、KeyError:0 で落ちた（2026-09-05 実測）。
    #   データの形は**現物を見てから書く**こと。
    w = (pack.get("weather") or {}).get("regions") or []
    if not w:
        return _pick([
            "今日の空模様は、窓の外をのぞいて確かめてちょうだいね。",
            "空の機嫌は、出がけにその目で見ておきなさいね。",
        ], t, 7919)
    h = w[0]
    return _pick([
        f"今日の{h['region']}は{h['text']}。最高気温は{round(h['temp_max'])}度の見込みよ。",
        f"{h['region']}のほうは{h['text']}ですって。{round(h['temp_max'])}度まで上がるみたいね。",
        f"今朝の{h['region']}、{h['text']}よ。{round(h['temp_max'])}度、覚えておきなさいね。",
    ], t, 7919)


def _song(pack: dict, key: str) -> tuple[str, str]:
    s = pack.get(key)
    if isinstance(s, dict):
        return s.get("title", ""), s.get("artist", "")
    return (s or ""), ""


def _seg(name: str, body: str) -> str:
    return f"===SEGMENT: {name}===\n{body.strip()}\n\n"


def build(pack: dict) -> str:
    import datetime
    try:
        t = datetime.date.fromisoformat(pack.get("date", "")).toordinal()
    except Exception:
        t = datetime.date.today().toordinal()

    d, wd = pack.get("date_ja", ""), pack.get("weekday_ja", "")
    t1, a1 = _song(pack, "song1")
    t2, a2 = _song(pack, "song2")
    theme = pack.get("theme_of_today", "今日これから、ひとつだけ頑張ること")
    sa = pack.get("sa_of_today") or {}

    # ★オープニングの定型挨拶は崩さない（nordw指定）。後ろだけ替える
    boshu = _pick([
        "チャット欄に書き込んでちょうだいね。この後の曲を聴いてる間でいいからね。"
        "番組の後半、交通情報のあとでちゃんと読むわよ。",
        "思いついたらチャット欄に書いてちょうだい。曲がかかってる間でいいのよ。"
        "後半、交通情報が終わったら読んでいくからね。",
        "チャット欄で待ってるわよ。次の曲を聴きながらでいいから、ひとこと書いてね。"
        "番組の後半、交通情報のあとで読むわよ。",
    ], t, 4001)
    shokai = _pick([
        f"それでは一曲目、聴いてください——『{t1}』。",
        f"さあ一曲目にいきましょう。聴いてください——『{t1}』。",
        f"まずは一曲。聴いてちょうだい——『{t1}』。",
    ], t, 6197)
    utau1 = f"歌うのは{a1}よ。" if a1 else ""

    traffic = _pick([
        "交通情報の時間よ。今朝の高速道路は、大きな乱れの情報は入っていないわ。\n"
        "出かける前に、公式の道路交通情報でもう一度たしかめてちょうだいね。",
        "道路の話をひとつ。今のところ、目立った混雑の知らせは来ていないわね。\n"
        "とはいえ朝は変わりやすいから、出る前に公式の情報を見ておきなさいね。",
        "交通情報よ。いまのところ穏やかみたいね。\n"
        "運転するなら、公式の道路交通情報にも目を通してから出なさいね。",
    ], t, 5003)

    if sa.get("name"):
        sa_body = _pick([
            f"今日ご紹介するのは、{sa.get('route','')}の{sa.get('name','')}。"
            f"{sa.get('pref','')}にあるのよ。\n高速を使う予定があるなら、寄ってみるのもいいわね。",
            f"今日は{sa.get('pref','')}から、{sa.get('route','')}の{sa.get('name','')}。\n"
            f"通りかかったら、ひと休みしていきなさいね。",
            f"サービスエリアの話ね。{sa.get('route','')}にある{sa.get('name','')}よ。\n"
            f"{sa.get('pref','')}ね。長い運転の途中に、ちょうどいい場所だと思うわ。",
        ], t, 3571)
    else:
        sa_body = "サービスエリアの話は、また明日ゆっくりね。"

    # ★ニュースのフォールバック（2026-09-05）。
    #   ★★見出しを読み上げてはいけない。LLMが無い＝安全に要約する手段が無い、ということ。
    #     ニュースの固有名詞は毎朝新しく降ってくるので合成が読み違える
    #     （実測「灘崎小迫川分校」→「ナダサキショーハザカワブンコー」）。
    #     見出しの丸読みは権利の面でも危ない。**だから読まずに畳む。**
    #   ただし「サイバー演歌」レーンだけは別。曲名・歌手名は辞書で読みを作ってあるので
    #   安全に読める。うちの局の話でもあるので、ここだけは拾う。
    ours = [i for i in (pack.get("news") or {}).get("items", [])
            if i.get("lane") == "サイバー演歌"]
    if ours:
        news = _pick([
            f"ニュースをひとつだけ。うちの局の公式チャンネルに"
            f"「{ours[0]['title']}」が上がってるわよ。まだの人は覗いてみてちょうだいね。",
            f"お知らせをひとつ。公式チャンネルで「{ours[0]['title']}」が聴けるわ。\n"
            f"よかったら、あとで寄っていってちょうだいね。",
        ], t, 8221)
    else:
        news = _pick([
            "今日のニュースコーナーは、お休みさせてちょうだい。\n"
            "世の中いろいろ動いてるけど、あなたの朝が穏やかなら、それで十分よ。",
            "ニュースはまた明日にするわね。\n"
            "急がなくていいのよ。まずは今日一日を、ちゃんと歩きなさいね。",
            "今日はニュースは短めにするわ。\n"
            "遠くの話より、目の前のことよ。あなたの一日のほうが、よっぽど大事だもの。",
        ], t, 7919)

    mail = _pick([
        f"今日のテーマは「{theme}」だったわね。\n"
        "あたしからも一つ。欲張らないでいいのよ、ひとつ決めたらそれだけ。"
        "それだけで今日はじゅうぶん上出来。",
        f"「{theme}」がテーマだったわね。\n"
        "全部やろうとするから重たくなるのよ。ひとつでいいの、ひとつで。",
        f"テーマは「{theme}」。\n"
        "あたしね、こういうのは決めた時点でもう半分終わってると思ってるのよ。",
    ], t, 2749)
    shokai2 = _pick([
        f"それじゃあ二曲目、聴いてちょうだい——『{t2}』。",
        f"さあ、二曲目にいきましょう——『{t2}』。",
        f"ここで一曲。聴いてください——『{t2}』。",
    ], t, 6197)
    utau2 = f"歌うのは{a2}よ。" if a2 else ""

    uranai = _pick([
        "占いのお時間。今日はどの星座も、まずまずの運勢よ。\n"
        "ラッキーアイテムは、あたたかい飲み物。ひと息つく時間を、ちゃんと取りなさいね。",
        "今日の占いね。星の並びは、どこも悪くないわ。\n"
        "ラッキーアイテムは、使い慣れた文房具。手に馴染むものが味方してくれる日よ。",
        "占いいくわよ。今日は大きな山も谷も無い、静かな日みたいね。\n"
        "ラッキーアイテムは、明るい色のハンカチ。目に入るところに置いておきなさいね。",
    ], t, 4409)

    ending = _pick([
        "サイバー演歌モーニング、今日はここまで。\n"
        "あなたの一日に、ちゃんと火がつきますように。また明日の朝も、ここで会いましょう。",
        "さあ、今日の放送はここまでよ。\n"
        "無理はしなくていいから、ちゃんと生きてちょうだいね。また明日の朝ね。",
        "サイバー演歌モーニング、そろそろお別れの時間ね。\n"
        "今日という日が、あなたにとって悪くない一日になりますように。またここで待ってるわよ。",
    ], t, 5297)

    out = ""
    out += _seg("talk1", f"""
おはようございます！{d}{wd}、サイバー演歌モーニング。パーソナリティの雷音こずえです！
{_weather_line(pack, t)}
さて、今日のおたよりのテーマはこれよ。「{theme}」。
{boshu}
{shokai}{utau1}
""")
    out += _seg("traffic", traffic)
    out += _seg("sa", sa_body)
    out += _seg("news", news)
    out += _seg("mail_fb", f"{mail}\n{shokai2}{utau2}")
    out += _seg("uranai", uranai)
    out += _seg("ending", ending)
    return out.rstrip() + "\n"


def demo() -> None:
    """★何日か分を並べて、本当に日替わりで変わるかを目で見る。"""
    import datetime
    pack = {"date_ja": "2026年9月5日", "weekday_ja": "金曜日", "date": "2026-09-05",
            "theme_of_today": "今日これから、ひとつだけ頑張ること",
            "weather": {"regions": [{"region": "関東", "text": "小雨", "temp_max": 27.0}]},
            "sa_of_today": {"name": "田野パーキングエリア", "route": "常磐自動車道",
                            "pref": "茨城県"},
            "song1": {"title": "南の星", "artist": "灯じゅん"},
            "song2": {"title": "紅の糸", "artist": "雷音こずえ"}}
    seen = set()
    for k in range(14):
        day = datetime.date(2026, 9, 5) + datetime.timedelta(days=k)
        pack["date"] = day.isoformat()
        s = build(pack)
        seen.add(s)
        if k < 5:
            print(f"{day} {s.splitlines()[6][:52]}")
    # ★3択×6ブロック。14日ぶんで**同じ台本が出ない**ことを確かめる
    assert len(seen) == 14, f"14日ぶんで {len(seen)}種類しか出ていない"
    print("OK 14日ぶん、全部ちがう台本になった")


if __name__ == "__main__":
    import sys
    sys.stdout.reconfigure(encoding="utf-8")
    demo()
