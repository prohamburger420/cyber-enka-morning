REF_BY_CORNER: dict[str, tuple[str, str]] = {}


def resolve(ref_dir) -> dict:
    """ファイル名を、渡されたディレクトリ配下の実パスに解決して返す。

    返り値は {コーナー名: (Path, 書き起こし)}。既定は "" のキーに入れる。
    """
    from pathlib import Path
    d = Path(ref_dir)
    out = {"": (d / REF_DEFAULT[0], REF_DEFAULT[1])}
    for k, (f, t) in REF_BY_CORNER.items():
        out[k] = (d / f, t)
    return out
